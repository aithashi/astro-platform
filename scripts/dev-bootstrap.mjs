#!/usr/bin/env node
// Local dev setup, safe to re-run: writes apps/web/.env.local from the running local
// Supabase stack and creates a test owner + admin login. Local stack only.
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const STAFF = [
  { email: "owner@astro.local", display_name: "Owner (dev)", role: "owner" },
  { email: "admin@astro.local", display_name: "Admin (dev)", role: "admin" },
];

function status() {
  const out = execFileSync("pnpm", ["exec", "supabase", "status", "-o", "json"], { cwd: root, encoding: "utf8" });
  const s = JSON.parse(out.slice(out.indexOf("{")));
  const pick = (...keys) => keys.map((k) => s[k]).find(Boolean);
  const env = {
    apiUrl: pick("API_URL"),
    publishableKey: pick("PUBLISHABLE_KEY", "ANON_KEY"),
    secretKey: pick("SECRET_KEY", "SERVICE_ROLE_KEY"),
    studioUrl: pick("STUDIO_URL"),
    mailUrl: pick("MAILPIT_URL", "INBUCKET_URL"),
  };
  if (!env.apiUrl || !env.publishableKey || !env.secretKey) {
    throw new Error(`Unexpected \`supabase status\` output; keys found: ${Object.keys(s).join(", ")}`);
  }
  if (!/127\.0\.0\.1|localhost/.test(env.apiUrl)) throw new Error(`Refusing to run against non-local ${env.apiUrl}`);
  return env;
}

async function api(env, path, init = {}) {
  const res = await fetch(`${env.apiUrl}${path}`, {
    ...init,
    headers: {
      apikey: env.secretKey,
      Authorization: `Bearer ${env.secretKey}`,
      "Content-Type": "application/json",
      ...init.headers,
    },
  });
  const body = await res.text();
  if (!res.ok) throw new Error(`${init.method ?? "GET"} ${path} -> ${res.status} ${body}`);
  return body ? JSON.parse(body) : null;
}

async function ensureUser(env, email) {
  const { users } = await api(env, "/auth/v1/admin/users?per_page=1000");
  const existing = users.find((u) => u.email === email);
  if (existing) return existing.id;
  const created = await api(env, "/auth/v1/admin/users", {
    method: "POST",
    body: JSON.stringify({ email, email_confirm: true }),
  });
  return created.id;
}

const env = status();

const envFile = `${root}apps/web/.env.local`;
if (existsSync(envFile)) {
  console.log("apps/web/.env.local exists, leaving it alone");
} else {
  writeFileSync(
    envFile,
    `# Generated by scripts/dev-bootstrap.mjs for the local Supabase stack.\n` +
      `VITE_SUPABASE_URL=${env.apiUrl}\nVITE_SUPABASE_PUBLISHABLE_KEY=${env.publishableKey}\nVITE_DEFAULT_WHATSAPP=919999999999\n`,
  );
  console.log("wrote apps/web/.env.local");
}

for (const s of STAFF) {
  const user_id = await ensureUser(env, s.email);
  await api(env, "/rest/v1/staff?on_conflict=user_id", {
    method: "POST",
    headers: { Prefer: "resolution=merge-duplicates,return=minimal" },
    body: JSON.stringify({ user_id, display_name: s.display_name, role: s.role }),
  });
  console.log(`staff ready: ${s.email} (${s.role})`);
}

console.log(`
Sign in at http://localhost:5173/admin/login with one of the emails above.
The magic link arrives in the local mail inbox: ${env.mailUrl ?? "http://127.0.0.1:54324"}
Studio: ${env.studioUrl ?? "http://127.0.0.1:54323"}`);
